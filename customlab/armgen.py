"""Generate Unlimbited Arm parts from the OFFICIAL SCAD supplied locally by the user (never embedded).

Results are cached by (SCAD hash, parameters). Each cached part gets README.txt / LICENSE.txt in the same folder, written in the
format used by Thingiverse archives, so the licence (CC BY-NC-SA, attribution) travels with the part into the export sheet.
"""
import hashlib
import json
import os
import shutil
import tempfile
from pathlib import Path

from . import openscad, paths
from .profiles import load_profile

ROOT = Path(__file__).resolve().parent.parent


def home():
    return Path(os.environ.get("CUSTOMLAB_HOME") or Path.home() / ".customlab")


def scad_path(profile):
    rel = profile.get("official_scad")
    p = paths.resolve(rel) if rel else None
    if rel and not (p and p.is_file()): p = paths.find_file(Path(rel).name, "unlimbited_arm")      # the downloaded archive may be laid out differently
    return p if (p and p.is_file()) else None


def cache_key(scad, defines):
    h = hashlib.sha256(Path(scad).read_bytes()).hexdigest()[:12]
    return hashlib.sha256((h + json.dumps(defines, sort_keys=True)).encode()).hexdigest()[:16]


def generate_part(device_id, defines, cache_dir=None, timeout=1800):
    """Render one part and return (stl_path, from_cache). Raises RuntimeError with a clear message if SCAD/OpenSCAD is missing."""
    prof = load_profile(device_id); scad = scad_path(prof)
    if scad is None: raise RuntimeError(f"Fichier SCAD officiel introuvable : {prof.get('official_scad')} (à télécharger depuis Thingiverse).")
    key = cache_key(scad, defines); folder = Path(cache_dir or home() / "generated") / f"{device_id}_{key}"
    part, side = defines.get(prof["part_param"], "part"), str(defines.get(prof["scad_params_side"]["param"], "")).lower()
    out = folder / f"{part}_{side}.stl"
    if out.is_file(): return out, True
    folder.mkdir(parents=True, exist_ok=True)
    if not openscad.find_openscad(): raise openscad.OpenSCADUnavailable("OpenSCAD introuvable (tools/OpenSCAD.app ou installation système).")
    with tempfile.TemporaryDirectory() as d:
        tmp = openscad.render(scad, Path(d) / "o.stl", defines, timeout=timeout); shutil.copyfile(tmp, out)
    params = ", ".join(f"{k}={v}" for k, v in defines.items())
    lic_src = scad.parent.parent / "LICENSE.txt"
    lic_txt = lic_src.read_text(encoding="utf-8").strip() if lic_src.is_file() else "Creative Commons - Attribution - Non-Commercial - Share Alike"
    (folder / "README.txt").write_text(
        f"The UnLimbited Arm v2.1 (Alfie Edition) - {part} ({side}) by Team_UnLimbited is licensed under the Creative Commons - Attribution - Non-Commercial - Share Alike license.\n"
        f"http://creativecommons.org/licenses/by-nc-sa/4.0/\nCustomized version of http://www.thingiverse.com/thing:1672381\n"
        f"Generated by CustomLab with the official OpenSCAD file {scad.name}; parameters: {params}.\n", encoding="utf-8")
    (folder / "LICENSE.txt").write_text(lic_txt + "\n", encoding="utf-8")
    return out, False
